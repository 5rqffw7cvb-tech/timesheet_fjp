export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "en" ? "en" : "ja";
}

export function getMessage(locale: Locale, key: keyof typeof MESSAGES.ja, params?: Record<string, string | number>) {
  const message = MESSAGES[locale][key] ?? MESSAGES.ja[key] ?? MESSAGES.en[key];
  if (!params) return message;
  return String(message).replace(/\{(\w+)\}/g, (_, param: string) => String(params[param] ?? ""));
}

export function formatNumber(locale: Locale, value: number) {
  return value.toLocaleString(locale === "ja" ? "ja-JP" : "en-US");
}
